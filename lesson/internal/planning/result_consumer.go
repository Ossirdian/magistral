package planning

import (
	"context"
	"encoding/json"
	"errors"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/ossirdian/magistral/lesson/internal/model"
	"github.com/ossirdian/magistral/platform/pkg/logger"
	ptracing "github.com/ossirdian/magistral/platform/pkg/tracing"
	"github.com/segmentio/kafka-go"
	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/attribute"
	"go.opentelemetry.io/otel/propagation"
	"go.opentelemetry.io/otel/trace"
)

type BatchApplier interface {
	ApplyBatch(ctx context.Context, schoolID string, input model.BatchApplyRequest) (model.BatchApplyResult, error)
}

type ResultConsumer struct {
	reader  *kafka.Reader
	applier BatchApplier
	status  *StatusStore
}

func NewResultConsumer(brokers []string, topic string, groupID string, applier BatchApplier, status *StatusStore) (*ResultConsumer, error) {
	topic = strings.TrimSpace(topic)
	groupID = strings.TrimSpace(groupID)
	if len(brokers) == 0 || topic == "" || groupID == "" {
		return nil, ErrNotConfigured
	}
	if applier == nil {
		return nil, errors.New("planning result applier is nil")
	}
	return &ResultConsumer{
		reader: kafka.NewReader(kafka.ReaderConfig{
			Brokers:        brokers,
			Topic:          topic,
			GroupID:        groupID,
			CommitInterval: 0,
			MinBytes:       1,
			MaxBytes:       10e6,
		}),
		applier: applier,
		status:  status,
	}, nil
}

func (c *ResultConsumer) Close() error {
	if c == nil || c.reader == nil {
		return nil
	}
	return c.reader.Close()
}

func (c *ResultConsumer) Run(ctx context.Context) error {
	if c == nil || c.reader == nil {
		return ErrNotConfigured
	}

	logger.Global().Info("starting planning result consumer")
	for {
		message, err := c.reader.FetchMessage(ctx)
		if err != nil {
			if errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded) {
				return nil
			}
			return err
		}

		if err := c.applyMessage(ctx, message.Value); err != nil {
			logger.Global().Error("failed to apply planning result", "error", err)
		}
		if err := c.reader.CommitMessages(ctx, message); err != nil {
			return err
		}
	}
}

func (c *ResultConsumer) applyMessage(ctx context.Context, payload []byte) error {
	var result ResultMessage
	if err := json.Unmarshal(payload, &result); err != nil {
		return err
	}

	ctx = otel.GetTextMapPropagator().Extract(ctx, propagation.MapCarrier(result.TraceContext))
	ctx, span := ptracing.StartSpan(ctx, "lesson.planning.apply_result",
		trace.WithAttributes(
			attribute.String("planning.request_id", result.RequestID),
			attribute.String("planning.school_id", result.SchoolID),
			attribute.Int("planning.result.lessons", len(result.Lessons)),
			attribute.Int("planning.result.conflicts", len(result.Conflicts)),
		),
	)
	defer span.End()

	applyCtx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()

	batch := result.toBatchApplyRequest()
	if len(batch.Lessons) == 0 {
		span.SetAttributes(attribute.Bool("planning.apply.skipped", true))
		c.status.SaveCompleted(result.SchoolID, result, 0, true)
		logger.Global().Info("planning result has no valid lessons to apply", "request_id", result.RequestID, "school_id", result.SchoolID)
		return nil
	}

	applied, err := c.applier.ApplyBatch(applyCtx, result.SchoolID, batch)
	if err != nil {
		span.RecordError(err)
		return err
	}
	span.SetAttributes(
		attribute.Int("planning.apply.requested", applied.Requested),
		attribute.Int("planning.apply.applied", applied.Applied),
		attribute.Int("planning.apply.conflicts", len(applied.Conflicts)),
		attribute.Bool("planning.apply.successful", applied.Successful),
	)
	c.status.SaveCompleted(result.SchoolID, result, applied.Applied, applied.Successful)
	logger.Global().Info(
		"planning result applied",
		"request_id", result.RequestID,
		"school_id", result.SchoolID,
		"requested", applied.Requested,
		"applied", applied.Applied,
		"conflicts", len(applied.Conflicts),
		"successful", applied.Successful,
	)
	return nil
}

func (r ResultMessage) toBatchApplyRequest() model.BatchApplyRequest {
	mode := model.BatchReplaceMode(strings.TrimSpace(r.ReplaceStrategy))
	if mode == "" {
		mode = model.BatchReplaceModeAppend
	}

	lessons := make([]model.BatchLessonUpsert, 0, len(r.Lessons))
	for _, item := range r.Lessons {
		if !validResultLesson(item) {
			continue
		}
		lessons = append(lessons, model.BatchLessonUpsert{
			BranchID:     item.BranchID,
			StudentID:    item.StudentID,
			InstructorID: item.InstructorID,
			CarID:        item.CarID,
			StartAt:      item.StartAt,
			EndAt:        item.EndAt,
			Comment:      resultComment(r.RequestID),
		})
	}
	return model.BatchApplyRequest{
		Mode:    mode,
		Lessons: lessons,
	}
}

func resultComment(requestID string) *string {
	requestID = strings.TrimSpace(requestID)
	if requestID == "" {
		comment := "generated by planning"
		return &comment
	}
	comment := "generated by planning request " + requestID
	return &comment
}

func validResultLesson(item ResultLesson) bool {
	if _, err := uuid.Parse(strings.TrimSpace(item.StudentID)); err != nil {
		return false
	}
	if _, err := uuid.Parse(strings.TrimSpace(item.InstructorID)); err != nil {
		return false
	}
	if _, err := uuid.Parse(strings.TrimSpace(item.CarID)); err != nil {
		return false
	}
	if item.BranchID != nil {
		if _, err := uuid.Parse(strings.TrimSpace(*item.BranchID)); err != nil {
			return false
		}
	}
	return item.StartAt.Before(item.EndAt)
}
