#!/bin/sh
set -eu

export PGPASSWORD="${POSTGRES_PASSWORD}"

psql -v ON_ERROR_STOP=1 --username "${POSTGRES_USER}" --dbname "${POSTGRES_DB}" <<EOSQL
DO \$\$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${RESOURCES_POSTGRES_USER}') THEN
        CREATE ROLE ${RESOURCES_POSTGRES_USER} LOGIN PASSWORD '${RESOURCES_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${RESOURCES_POSTGRES_USER} WITH LOGIN PASSWORD '${RESOURCES_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${SAAS_POSTGRES_USER}') THEN
        CREATE ROLE ${SAAS_POSTGRES_USER} LOGIN PASSWORD '${SAAS_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${SAAS_POSTGRES_USER} WITH LOGIN PASSWORD '${SAAS_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${IAM_POSTGRES_USER}') THEN
        CREATE ROLE ${IAM_POSTGRES_USER} LOGIN PASSWORD '${IAM_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${IAM_POSTGRES_USER} WITH LOGIN PASSWORD '${IAM_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${LESSON_POSTGRES_USER}') THEN
        CREATE ROLE ${LESSON_POSTGRES_USER} LOGIN PASSWORD '${LESSON_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${LESSON_POSTGRES_USER} WITH LOGIN PASSWORD '${LESSON_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${STUDENT_POSTGRES_USER}') THEN
        CREATE ROLE ${STUDENT_POSTGRES_USER} LOGIN PASSWORD '${STUDENT_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${STUDENT_POSTGRES_USER} WITH LOGIN PASSWORD '${STUDENT_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${PAYMENT_POSTGRES_USER}') THEN
        CREATE ROLE ${PAYMENT_POSTGRES_USER} LOGIN PASSWORD '${PAYMENT_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${PAYMENT_POSTGRES_USER} WITH LOGIN PASSWORD '${PAYMENT_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${DOCUMENT_POSTGRES_USER}') THEN
        CREATE ROLE ${DOCUMENT_POSTGRES_USER} LOGIN PASSWORD '${DOCUMENT_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${DOCUMENT_POSTGRES_USER} WITH LOGIN PASSWORD '${DOCUMENT_POSTGRES_PASSWORD}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${AUDIT_POSTGRES_USER}') THEN
        CREATE ROLE ${AUDIT_POSTGRES_USER} LOGIN PASSWORD '${AUDIT_POSTGRES_PASSWORD}';
    ELSE
        ALTER ROLE ${AUDIT_POSTGRES_USER} WITH LOGIN PASSWORD '${AUDIT_POSTGRES_PASSWORD}';
    END IF;
END
\$\$;

SELECT 'CREATE DATABASE ${RESOURCES_POSTGRES_DB} OWNER ${RESOURCES_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${RESOURCES_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${SAAS_POSTGRES_DB} OWNER ${SAAS_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${SAAS_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${IAM_POSTGRES_DB} OWNER ${IAM_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${IAM_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${LESSON_POSTGRES_DB} OWNER ${LESSON_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${LESSON_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${STUDENT_POSTGRES_DB} OWNER ${STUDENT_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${STUDENT_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${PAYMENT_POSTGRES_DB} OWNER ${PAYMENT_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${PAYMENT_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${DOCUMENT_POSTGRES_DB} OWNER ${DOCUMENT_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${DOCUMENT_POSTGRES_DB}') \gexec

SELECT 'CREATE DATABASE ${AUDIT_POSTGRES_DB} OWNER ${AUDIT_POSTGRES_USER}'
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '${AUDIT_POSTGRES_DB}') \gexec
EOSQL
