from datetime import datetime, timezone
from pprint import pprint

from planning.app.data_loader import (
    DataLoader,
    LoadedPlanningData,
    _is_deleted_or_cancelled_lesson,
    _is_replaceable_generated_lesson,
    _target_lessons_by_student,
)
from planning.app.models import PlanningRequest, StudentPreference
from planning.app.planner import Planner


class StubDataLoader(DataLoader):
    def load(self, request: PlanningRequest) -> LoadedPlanningData:
        del request
        student_ids = [f"student-{index}" for index in range(1, 16)]
        targets = {student_id: 10 for student_id in student_ids}
        return LoadedPlanningData(
            student_ids=student_ids,
            target_lessons_by_student=targets,
            lesson_demands=[
                student_id
                for student_id, target_lessons in targets.items()
                for _index in range(target_lessons)
            ],
            instructor_ids=[f"instructor-{index}" for index in range(1, 11)],
            car_ids=[f"car-{index}" for index in range(1, 11)],
            existing_lessons=[],
            student_preferences={student_id: StudentPreference() for student_id in student_ids},
            student_transmissions={},
            car_transmissions={},
            instructor_availability={},
            car_availability={},
            diagnostics={},
        )


def test_planning_creates_schedule_limited_by_slots_and_cars() -> None:
    planner = Planner(StubDataLoader())
    request = PlanningRequest(
        school_id="school-1",
        period_start=datetime(2026, 4, 21, 9, 0, tzinfo=timezone.utc),
        period_end=datetime(2026, 4, 24, 20, 0, tzinfo=timezone.utc),
        student_ids=["student-1"],
        group_ids=[],
        branch_ids=[],
        replace_strategy="append",
        requested_by_user_id="user-1",
        request_id="request-1",
    )

    result = planner.plan(request)
    scheduled_by_student: dict[str, int] = {}
    for lesson in result.lessons:
        scheduled_by_student[lesson.student_id] = scheduled_by_student.get(lesson.student_id, 0) + 1

    print()
    print("Planning test result")
    pprint(
        {
            "request_id": result.request_id,
            "lessons": len(result.lessons),
            "unassigned_students": result.unassigned_students,
            "conflicts": [conflict.as_dict() for conflict in result.conflicts],
            "score": result.score,
            "score_breakdown": result.score_breakdown,
            "scheduled_by_student": scheduled_by_student,
            "first_lesson": result.lessons[0].as_dict() if result.lessons else None,
            "last_lesson": result.lessons[-1].as_dict() if result.lessons else None,
        },
        sort_dicts=False,
    )

    assert result.request_id == "request-1"
    assert len(result.lessons) == 150
    assert result.unassigned_students == []
    assert result.conflicts == []
    assert all(lesson.start_at.hour >= 8 for lesson in result.lessons)
    assert all(lesson.end_at.hour < 20 or (lesson.end_at.hour == 20 and lesson.end_at.minute == 0) for lesson in result.lessons)
    assert _is_replaceable_generated_lesson({"is_generated": True}) is True
    assert _is_replaceable_generated_lesson({"comment": "generated by planning request request-1"}) is True
    assert _is_replaceable_generated_lesson({"comment": "manual lesson"}) is False
    assert _is_deleted_or_cancelled_lesson({"deleted_at": "2026-05-26T10:00:00Z"}) is True
    assert _is_deleted_or_cancelled_lesson({"status": "cancelled"}) is True
    assert _is_deleted_or_cancelled_lesson({"status": "scheduled"}) is False


def test_target_lessons_prefer_lesson_count_over_hours() -> None:
    targets = _target_lessons_by_student(
        [
            {"id": "student-manual", "remaining_lessons_required_max": 28, "remaining_hours": 54},
            {"id": "student-auto", "remaining_lessons_required_max": 27, "remaining_hours": 54},
            {"id": "student-zero", "remaining_lessons_required_max": 0, "remaining_hours": 54},
            {"id": "student-hours-fallback", "remaining_hours": 42},
        ]
    )

    assert targets == {
        "student-manual": 28,
        "student-auto": 27,
        "student-zero": 0,
        "student-hours-fallback": 28,
    }


def test_target_lessons_cap_hour_fallback_by_transmission_program() -> None:
    targets = _target_lessons_by_student(
        [
            {"id": "student-manual", "program_id": "program-manual", "remaining_hours": 54},
            {"id": "student-auto", "program_id": "program-auto", "remaining_hours": 54},
            {
                "id": "student-started",
                "program_id": "program-manual",
                "remaining_hours": 39,
                "total_hours_completed": 15,
            },
        ],
        {"program-manual": "manual", "program-auto": "automatic"},
    )

    assert targets == {
        "student-manual": 28,
        "student-auto": 27,
        "student-started": 18,
    }
